"""The spray paint's colour names: 256 colours spaced evenly over HSV, each named after the nearest common colour name
from the xkcd colour survey (xkcd_rgb.txt, CC0: https://xkcd.com/color/rgb.txt), written as a C# table the game looks
the body's colour up in (unity/Assets/Scripts/Wardrobe/ColorNames.cs).

    python3 art/colors/make_color_names.py

The grid: 21 hues (every ~17 degrees) x 3 saturations (0.45, 0.75, 1) x 4 values (0.4, 0.6, 0.8, 1) = 252 colours, plus
4 greys (black, dark grey, light grey, white) = 256: the washed-out and near-black corners, which all read as grey,
are left to those four. Each cell takes the nearest name no other cell has (when one of its 12 nearest is free), so
the names hardly repeat. Distance is a plain vector distance in the HSV cone (x = s*v*cos h, y = s*v*sin h, z = v), so hue
wraps round (359 and 1 degrees are neighbours) and greys don't care about their hue. The game measures the same way.
Names about bodily fluids are left out ("puke green"); "ugly" and "muddy" ones stay (good material for a roast).
"""
import colorsys
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, "xkcd_rgb.txt")
OUT = os.path.join(os.path.dirname(os.path.dirname(HERE)), "unity", "Assets", "Scripts", "Wardrobe", "ColorNames.cs")
SKIP = ("puke", "vomit", "poo", "shit", "barf", "booger", "snot", "diarrh", "piss", "bile", "sick")


def cone(h, s, v):
    a = 2 * math.pi * h
    return (s * v * math.cos(a), s * v * math.sin(a), v)


def survey():
    out = []
    with open(SOURCE, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or "\t" not in line:
                continue
            name, hexcode = line.split("\t")[:2]
            if any(w in name for w in SKIP):
                continue
            r, g, b = (int(hexcode.strip()[i:i + 2], 16) / 255 for i in (1, 3, 5))
            out.append((name.strip(), cone(*colorsys.rgb_to_hsv(r, g, b))))
    return out


def grid():
    cells = [(h / 21, s, v) for h in range(21) for s in (0.45, 0.75, 1.0) for v in (0.4, 0.6, 0.8, 1.0)]
    cells += [(0.0, 0.0, v / 3) for v in range(4)]
    return cells


def assign(cells, names, k=12):
    """A name per cell: the nearest one not taken yet, the closest-matched cells choosing first; a cell whose k
    nearest are all taken shares its nearest."""
    near = []
    for c in cells:
        p = cone(*c)
        near.append(sorted(names, key=lambda n: math.dist(n[1], p))[:k])
    order = sorted(range(len(cells)), key=lambda i: math.dist(near[i][0][1], cone(*cells[i])))
    taken, out = set(), [None] * len(cells)
    for i in order:
        pick = next((n for n in near[i] if n[0] not in taken), near[i][0])
        taken.add(pick[0])
        out[i] = pick[0]
    return out


def main():
    names = survey()
    cells = grid()
    rows = [f'            new({h:.4f}f, {s:.4f}f, {v:.4f}f, "{name}"),' for (h, s, v), name in zip(cells, assign(cells, names))]
    code = f'''// Generated by art/colors/make_color_names.py from the xkcd colour survey (CC0): don't edit by hand.
// 256 colours spaced evenly over HSV (21 hues x 3 saturations x 4 values, plus 4 greys), each with the nearest common
// name no other one has. Nearest(colour) names any colour after the closest of them, by vector distance in the HSV cone (hue as an
// angle round it, saturation out from the middle, value up it), so hue wraps round and greys ignore their hue.
using UnityEngine;

namespace Freestyle.Wardrobe
{{
    public static class ColorNames
    {{
        public readonly struct Entry
        {{
            public readonly float h, s, v;
            public readonly string name;
            public Entry(float h, float s, float v, string name) {{ this.h = h; this.s = s; this.v = v; this.name = name; }}
        }}

        public static readonly Entry[] All =
        {{
{chr(10).join(rows)}
        }};

        static Vector3 Cone(float h, float s, float v)
        {{
            float a = h * 2 * Mathf.PI;
            return new Vector3(s * v * Mathf.Cos(a), s * v * Mathf.Sin(a), v);
        }}

        /// <summary>The common name of the listed colour closest to this one (vector distance in the HSV cone).</summary>
        public static string Nearest(Color c)
        {{
            Color.RGBToHSV(c, out float h, out float s, out float v);
            var p = Cone(h, s, v);
            string best = All[0].name;
            float bestD = float.MaxValue;
            foreach (var e in All)
            {{
                float d = (Cone(e.h, e.s, e.v) - p).sqrMagnitude;
                if (d < bestD) {{ bestD = d; best = e.name; }}
            }}
            return best;
        }}
    }}
}}
'''
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(code)
    used = sorted({r.rsplit('"', 2)[1] for r in rows})
    print(f"wrote {len(rows)} colours ({len(used)} distinct names) from {len(names)} survey names -> {OUT}")


if __name__ == "__main__":
    main()
